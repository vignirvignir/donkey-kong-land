// All character/enemy/item pixel art. 100% original artwork.
// Grid chars: '.' transparent, '0'..'3' = palette shade (0 lightest).

function S(str) {
  const rows = str.split('\n').map(r => r.trim()).filter(r => r.length);
  const w = Math.max(...rows.map(r => r.length));
  const h = rows.length;
  const data = new Int8Array(w * h).fill(-1);
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const c = row[x];
      if (c >= '0' && c <= '3') data[y * w + x] = c.charCodeAt(0) - 48;
    }
  });
  return { w, h, data };
}

